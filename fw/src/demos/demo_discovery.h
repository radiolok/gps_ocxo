#pragma once

#include "../display/ilc1_8.h"

/*
 * Демо: обнаружение карты сегментов.
 *
 * Последовательно зажигает по ОДНОМУ биту фреймбуфера (0..127),
 * позволяя экспериментально определить, какой бит SN755870
 * соответствует какому сегменту индикатора.
 *
 * Управление:
 *   - Автоматически перебирает биты с интервалом ~1.5 сек.
 *   - Текущий номер бита выводится в Serial (115200 бод).
 *   - После прохода всех 128 битов останавливается.
 *
 * Порядок работы:
 *   1. Подключить индикатор, загрузить прошивку.
 *   2. Открыть Serial Monitor (115200 бод).
 *   3. Наблюдать какой сегмент загорается при каждом номере бита.
 *   4. Записать соответствие в segment_map.h.
 *   5. Можно закомментировать/удалить этот файл после составления карты.
 */

namespace demo {

class DemoDiscovery {
public:
    DemoDiscovery(ILC1_8Display& display);

    void begin();
    void run();

private:
    ILC1_8Display& _disp;
    int            _currentBit;   // 0..127, -1 = done
    unsigned long  _lastUpdate;
    bool           _reported;     // уже вывели в Serial текущий бит
};

} // namespace demo
